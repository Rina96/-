#!/bin/bash

###############################################################################
# 🚀 QUICK START - Запустить Julia AI
# Usage: bash START.sh
###############################################################################

set -e

echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║         🚀 JULIA AI - QUICK START                          ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""

# ============================================================================
# Шаг 1: Запусти Colima
# ============================================================================

echo "🐳 ЭТАП 1: Запуск Colima (Docker runtime)..."
echo ""

if ! command -v colima &> /dev/null; then
    echo "❌ Colima не установлен"
    echo "Установи: brew install colima docker"
    exit 1
fi

# Проверь статус
if colima status > /dev/null 2>&1; then
    echo "✅ Colima уже работает"
else
    echo "Запускаю Colima... (первый раз может занять 2-3 мин)"
    colima start
    echo "✅ Colima запущен"
fi

echo ""

# ============================================================================
# Шаг 2: Проверь Docker
# ============================================================================

echo "✅ ЭТАП 2: Проверка Docker..."
echo ""

if docker ps > /dev/null 2>&1; then
    echo "✅ Docker работает"
    echo "   Version: $(docker --version)"
else
    echo "❌ Docker не работает"
    exit 1
fi

echo ""

# ============================================================================
# Шаг 3: Запусти deployment
# ============================================================================

echo "🚀 ЭТАП 3: Запуск Julia AI Deployment..."
echo ""

bash auto-deploy.sh
